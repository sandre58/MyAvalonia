namespace MyNet.Avalonia.Theme.Classes.Enums;

/// <summary>
/// Enumerates standard font sizes for use in the theming system.
/// Each value represents a predefined font size for consistent text styling.
/// </summary>
public enum FontSize
{
    /// <summary>
    /// Extra small font size.
    /// </summary>
    Xs,

    /// <summary>
    /// Small font size.
    /// </summary>
    Sm,

    /// <summary>
    /// Medium font size.
    /// </summary>
    Md,

    /// <summary>
    /// Large font size.
    /// </summary>
    Lg,

    /// <summary>
    /// Extra large font size.
    /// </summary>
    Xl,

    /// <summary>
    /// Represents the H6 heading level in a document.
    /// </summary>
    H6,

    /// <summary>
    /// Represents the H5 font size option.
    /// </summary>
    H5,

    /// <summary>
    /// Represents the H4 heading level, typically used for subheadings in a document or user interface.
    /// </summary>
    H4,

    /// <summary>
    /// Represents the H3 heading level in a document, typically used for sub-sections.
    /// </summary>
    H3,

    /// <summary>
    /// Represents the H2 heading level, which is commonly used for main section titles in a document or user interface.
    /// </summary>
    H2,

    /// <summary>
    /// Represents the H1 heading level, typically used for the main title or primary heading in a document or user interface.
    /// </summary>
    H1
}
