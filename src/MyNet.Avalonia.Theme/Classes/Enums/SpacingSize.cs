namespace MyNet.Avalonia.Theme.Classes.Enums;

/// <summary>
/// Enumerates standard thickness sizes (such as margin or padding) for use in the theming system.
/// Each value represents a predefined thickness value for consistent layout spacing.
/// </summary>
public enum SpacingSize
{
    /// <summary>
    /// No spacing.
    /// </summary>
    None,

    /// <summary>
    /// Small spacing.
    /// </summary>
    Xxs,

    /// <summary>
    /// Small spacing.
    /// </summary>
    Xs,

    /// <summary>
    /// Default (medium) spacing.
    /// </summary>
    Sm,

    /// <summary>
    /// Medium spacing.
    /// </summary>
    Md,

    /// <summary>
    /// Large spacing.
    /// </summary>
    Lg,

    /// <summary>
    /// Extra large spacing.
    /// </summary>
    Xl,

    /// <summary>
    /// Huge spacing.
    /// </summary>
    Xxl,

    /// <summary>
    /// Huge spacing.
    /// </summary>
    Xxxl
}
