namespace MyNet.Avalonia.Theme.Theming.Core;

/// <summary>
/// Defines the theme context for color schemes.
/// </summary>
public enum ThemeContext
{
    /// <summary>
    /// Represents the default color scheme for standard UI elements.
    /// </summary>
    Default,

    /// <summary>
    /// Represents a high-contrast color scheme for improved visibility and accessibility.
    /// </summary>
    Contrast
}
