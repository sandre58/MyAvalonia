namespace MyNet.Avalonia.Theme.Enums;

/// <summary>
/// Enumerates standard icon sizes for use in the theming system.
/// Each value represents a predefined icon size category for consistent UI scaling.
/// </summary>
public enum IconSize
{
    /// <summary>
    /// Extra small icon size.
    /// </summary>
    ExtraSmall,

    /// <summary>
    /// Small icon size.
    /// </summary>
    Small,

    /// <summary>
    /// Default (medium) icon size.
    /// </summary>
    Default,

    /// <summary>
    /// Large icon size.
    /// </summary>
    Large,

    /// <summary>
    /// Extra large icon size.
    /// </summary>
    ExtraLarge
}
